/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  FPGA_Request_t request;
  FPGA_Settings_t settings;

  HAL_Init();
  SystemClock_Config();
  Platform_time_init(SystemCoreClock);
  MX_GPIO_Init();

  UART_init(SystemCoreClock, 115200U);
  I2C_init();

  while (1)
  {
      if (FPGA_receive_request(&request, 10U) != FPGA_PROTOCOL_OK)
      {
          continue;
      }

      switch (request.type)
      {
          case FPGA_REQUEST_SAVE:
              (void)EEPROM_save_preset(request.preset_id, &request.settings);
              break;

          case FPGA_REQUEST_LOAD:
              if (EEPROM_load_preset(request.preset_id, &settings))
              {
                  (void)FPGA_send_preset(request.preset_id, &settings, 50U);
              }
              break;
              
          default:
              break;
      }
  }

  while (1)
  {
  }
}

